// Generate the TypeScript client from the mod's OpenAPI document.
//
//   bun run generate:rimworld-client                 # spec/rimapi-openapi.json → src/generated/
//   bun run generate:rimworld-client --check         # fail when the tree is stale
//   bun run generate:rimworld-client --url http://localhost:8767
//
// One method per operation, its request and response types taken from the
// document: path and query parameters as one typed object, the body as its
// component, and the answer as ApiResult<T> where T is the schema the route
// declares in `data` (null for a route that reports nothing back). Operations
// whose entry cannot be typed are written as `Json` and listed in
// spec/thin.json instead of being guessed.
//
// Determinism: operations are sorted by path and method, schema properties by
// name, and the file carries no timestamp or machine name. Two runs over the
// same snapshot produce the same bytes.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import {
  METHODS,
  canonicalJson,
  fetchSpec,
  readSpecFile,
  refName,
  type JsonValue,
  type Method,
  type Operation,
  type Parameter,
  type Schema,
  type Spec,
} from "./spec";

const ROOT = resolve(import.meta.dir, "..");
const SPEC_FILE = "spec/rimapi-openapi.json";
const GENERATED_DIR = "src/generated";

const HEADER = `// Code generated by scripts/generate.ts from ${SPEC_FILE}. DO NOT EDIT.
// Regenerate with: bun run generate:rimworld-client
`;

export interface Generated {
  types: string;
  client: string;
  thin: string;
}

interface Entry {
  path: string;
  method: Method;
  operation: Operation;
}

interface ThinRoute {
  method: string;
  path: string;
  operationId: string;
  reasons: string[];
}

interface ThinField {
  schema: string;
  property: string;
  reason: string;
}

interface ThinReport {
  counts: {
    operations: number;
    typedRoutes: number;
    untypedRoutes: number;
    freeFormFields: number;
  };
  routes: ThinRoute[];
  fields: ThinField[];
}

export function generate(spec: Spec): Generated {
  const entries = operationsOf(spec);
  const routes: ThinRoute[] = [];
  const methodNames = new Set<string>();

  const types = renderTypes(spec);
  const body: string[] = [];

  for (const entry of entries) {
    const name = methodName(entry.operation);
    if (name === "call" || name === "constructor") {
      throw new Error(`${entry.operation.operationId} would shadow ${name} on RimApiBase`);
    }
    if (methodNames.has(name)) {
      throw new Error(`two operations map to the method ${name}`);
    }
    methodNames.add(name);

    const params = renderParams(entry.operation);
    if (params !== null) body.push(params, "");
  }

  body.push("export class RimApiClient extends RimApiBase {");
  for (const entry of entries) {
    const data = responseData(entry.operation, spec);
    if (data.thin.length > 0) {
      routes.push({
        method: entry.method.toUpperCase(),
        path: entry.path,
        operationId: entry.operation.operationId,
        reasons: data.thin,
      });
    }
    body.push(renderMethod(entry, data.type));
  }
  body.push("}", "");

  const needsJson = body.join("\n").includes("Json");
  const imports = [
    HEADER,
    `import { RimApiBase } from "../runtime";`,
    `import type { ApiResult${needsJson ? ", Json" : ""} } from "../runtime";`,
    `import type * as Types from "./types";`,
    "",
  ];

  const thin: ThinReport = {
    counts: {
      operations: entries.length,
      typedRoutes: entries.length - routes.length,
      untypedRoutes: routes.length,
      freeFormFields: freeFormFields(spec).length,
    },
    routes,
    fields: freeFormFields(spec),
  };

  return {
    types,
    client: [...imports, ...body].join("\n"),
    thin: canonicalJson(thin as unknown as JsonValue),
  };
}

function operationsOf(spec: Spec): Entry[] {
  const entries: Entry[] = [];
  for (const path of Object.keys(spec.paths).sort(compare)) {
    const item = spec.paths[path];
    if (!item) continue;
    for (const method of METHODS) {
      const operation = item[method];
      if (operation) entries.push({ path, method, operation });
    }
  }
  return entries;
}

function renderTypes(spec: Spec): string {
  const schemas = spec.components?.schemas ?? {};
  const lines: string[] = [
    HEADER,
    `import type { Json } from "../runtime";`,
    "",
    "// The ApiResult* envelope family is hand-written in ../runtime.ts, because",
    "// the client is generic over `data`; only the payload types are generated.",
    "",
  ];

  for (const name of Object.keys(schemas).filter((n) => !n.startsWith("ApiResult")).sort(compare)) {
    const schema = schemas[name];
    if (!schema) continue;
    const doc = docComment(schema.description, "");
    if (doc.length > 0) lines.push(...doc);
    if (schema.type === "object" && schema.properties && Object.keys(schema.properties).length > 0) {
      lines.push(`export interface ${name} {`);
      const required = new Set(schema.required ?? []);
      for (const key of Object.keys(schema.properties).sort(compare)) {
        const property = schema.properties[key];
        if (!property) continue;
        lines.push(...docComment(property.description, "  "));
        lines.push(
          `  ${propertyKey(key)}${required.has(key) ? "" : "?"}: ${tsType(property, "  ", "")};`,
        );
      }
      lines.push("}", "");
    } else {
      lines.push(`export type ${name} = ${tsType(schema, "", "")};`, "");
    }
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

function renderParams(operation: Operation): string | null {
  const parameters = operation.parameters ?? [];
  if (parameters.length === 0) return null;

  const ordered = [...parameters].sort((a, b) => {
    if (a.in !== b.in) return a.in === "path" ? -1 : 1;
    return compare(a.name, b.name);
  });

  const lines = [`export interface ${paramTypeName(operation)} {`];
  for (const parameter of ordered) {
    lines.push(...docComment(parameter.description, "  "));
    const required = parameter.in === "path" || parameter.required === true;
    lines.push(
      `  ${propertyKey(parameter.name)}${required ? "" : "?"}: ${tsType(parameter.schema, "  ", "Types.")};`,
    );
  }
  lines.push("}");
  return lines.join("\n");
}

function renderMethod(entry: Entry, responseType: string): string {
  const { path, method, operation } = entry;
  const parameters = operation.parameters ?? [];
  const pathParameters = parameters.filter((p) => p.in === "path");
  const queryParameters = parameters.filter((p) => p.in === "query");
  const body = requestBodySchema(operation);

  const args: string[] = [];
  if (parameters.length > 0) args.push(`params: ${paramTypeName(operation)}`);
  if (body) args.push(`body: ${tsType(body, "  ", "Types.")}`);

  const callOptions: string[] = [];
  if (queryParameters.length > 0) {
    const fields = queryParameters
      .map((p) => `${propertyKey(p.name)}: ${paramAccess(p.name)}`)
      .join(", ");
    callOptions.push(`query: { ${fields} }`);
  }
  if (body) callOptions.push("body");

  const callArgs = [
    JSON.stringify(method.toUpperCase()),
    pathExpression(path, pathParameters),
  ];
  if (callOptions.length > 0) callArgs.push(`{ ${callOptions.join(", ")} }`);

  const doc = ["  /**"];
  if (operation.summary) doc.push(`   * ${oneLine(operation.summary)}`);
  doc.push("   *", `   * ${method.toUpperCase()} ${path}`, "   */");

  return [
    ...doc,
    `  ${methodName(operation)}(${args.join(", ")}): Promise<ApiResult<${responseType}>> {`,
    `    return this.call<${responseType}>(${callArgs.join(", ")});`,
    "  }",
  ].join("\n");
}

function responseData(operation: Operation, spec: Spec): { type: string; thin: string[] } {
  const ref = operation.responses?.["200"]?.content?.["application/json"]?.schema?.$ref;
  if (!ref) return { type: "Json", thin: ["response has no schema"] };

  const name = refName(ref);
  if (name === "ApiResult") {
    return { type: "Json", thin: ["response points at the untyped envelope"] };
  }

  const component = spec.components?.schemas?.[name];
  if (!component) throw new Error(`missing response component ${name}`);

  const data = component.properties?.data;
  if (!data) {
    return { type: "Json", thin: [`response component ${name} has no data property`] };
  }
  if (data.type === "null") return { type: "null", thin: [] };
  if (!isTyped(data)) {
    return { type: "Json", thin: [`response data of ${name} has no schema`] };
  }
  return { type: tsType(data, "  ", "Types."), thin: [] };
}

function freeFormFields(spec: Spec): ThinField[] {
  const fields: ThinField[] = [];
  const schemas = spec.components?.schemas ?? {};
  for (const name of Object.keys(schemas).sort(compare)) {
    if (name.startsWith("ApiResult")) continue;
    const schema = schemas[name];
    if (!schema?.properties) continue;
    for (const property of Object.keys(schema.properties).sort(compare)) {
      const value = schema.properties[property];
      if (value && !isTyped(value)) {
        fields.push({ schema: name, property, reason: "property has no schema" });
      }
    }
  }
  return fields;
}

function requestBodySchema(operation: Operation): Schema | undefined {
  return operation.requestBody?.content?.["application/json"]?.schema;
}

function isTyped(schema: Schema): boolean {
  return Boolean(
    schema.$ref ??
      schema.type ??
      schema.enum ??
      schema.anyOf ??
      schema.oneOf ??
      schema.allOf,
  );
}

function tsType(schema: Schema | undefined, indent: string, refPrefix: string): string {
  if (!schema) return "Json";
  if (schema.$ref) return `${refPrefix}${refName(schema.$ref)}`;
  if (schema.enum && schema.enum.length > 0) {
    return union(schema.enum.map(literal));
  }

  const alternatives = schema.anyOf ?? schema.oneOf;
  if (alternatives && alternatives.length > 0) {
    return union(alternatives.map((item) => tsType(item, indent, refPrefix)));
  }
  if (schema.allOf && schema.allOf.length > 0) {
    return schema.allOf.map((item) => tsType(item, indent, refPrefix)).join(" & ");
  }

  const type = schema.type;
  if (Array.isArray(type)) return union(type.map(primitive));
  if (type === "array") {
    const item = tsType(schema.items, indent, refPrefix);
    return needsParens(item) ? `(${item})[]` : `${item}[]`;
  }
  if (type === "object") {
    const properties = schema.properties;
    if (properties && Object.keys(properties).length > 0) {
      const lines = ["{"];
      const required = new Set(schema.required ?? []);
      for (const key of Object.keys(properties).sort(compare)) {
        const property = properties[key];
        if (!property) continue;
        lines.push(...docComment(property.description, `${indent}  `));
        lines.push(
          `${indent}  ${propertyKey(key)}${required.has(key) ? "" : "?"}: ${tsType(property, `${indent}  `, refPrefix)};`,
        );
      }
      lines.push(`${indent}}`);
      return lines.join("\n");
    }
    if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
      return `Record<string, ${tsType(schema.additionalProperties, indent, refPrefix)}>`;
    }
    return "Json";
  }
  return primitive(type);
}

function primitive(type: string | undefined): string {
  switch (type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    default:
      return "Json";
  }
}

function union(parts: string[]): string {
  const unique = [...new Set(parts)];
  return unique.length === 1 ? unique[0]! : unique.join(" | ");
}

function needsParens(type: string): boolean {
  return type.includes(" | ") || type.includes(" & ");
}

function literal(value: JsonValue): string {
  return typeof value === "string" ? JSON.stringify(value) : String(value);
}

function methodName(operation: Operation): string {
  const name = camelCase(operation.operationId);
  return RESERVED.has(name) ? `${name}_` : name;
}

function paramTypeName(operation: Operation): string {
  return `${identifier(operation.operationId)}Params`;
}

function identifier(value: string): string {
  const cleaned = value.replace(/[^A-Za-z0-9_$]/g, "_");
  return /^[0-9]/.test(cleaned) ? `_${cleaned}` : cleaned;
}

function camelCase(value: string): string {
  const words = value
    .replace(/[^A-Za-z0-9]+/g, " ")
    .trim()
    .split(/\s+/)
    .filter((word) => word.length > 0);
  if (words.length === 0) throw new Error(`no method name in ${value}`);
  const [first, ...rest] = words;
  return (
    first!.charAt(0).toLowerCase() +
    first!.slice(1) +
    rest.map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join("")
  );
}

function propertyKey(key: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

function paramAccess(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? `params.${name}` : `params[${JSON.stringify(name)}]`;
}

function pathExpression(path: string, pathParameters: Parameter[]): string {
  if (pathParameters.length === 0) return JSON.stringify(path);
  const expression = path.replace(/\{([^}]+)\}/g, (_match, raw: string) => {
    const name = raw.split(":")[0] ?? raw;
    return `\${encodeURIComponent(String(${paramAccess(name)}))}`;
  });
  return `\`${expression}\``;
}

function docComment(text: string | undefined, indent: string): string[] {
  if (!text) return [];
  return [`${indent}/** ${oneLine(text)} */`];
}

function oneLine(text: string): string {
  return text.replace(/\s+/g, " ").replace(/\*\//g, "*\\/").trim();
}

function compare(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

const RESERVED = new Set([
  "await",
  "break",
  "case",
  "catch",
  "class",
  "const",
  "continue",
  "debugger",
  "default",
  "delete",
  "do",
  "else",
  "enum",
  "export",
  "extends",
  "false",
  "finally",
  "for",
  "function",
  "if",
  "implements",
  "import",
  "in",
  "instanceof",
  "interface",
  "let",
  "new",
  "null",
  "package",
  "private",
  "protected",
  "public",
  "return",
  "static",
  "super",
  "switch",
  "this",
  "throw",
  "true",
  "try",
  "typeof",
  "var",
  "void",
  "while",
  "with",
  "yield",
]);

function argument(name: string, fallback: string): string {
  const index = process.argv.indexOf(name);
  if (index < 0) return fallback;
  const value = process.argv[index + 1];
  if (value === undefined) throw new Error(`${name} needs a value`);
  return value;
}

if (import.meta.main) {
  const url = process.argv.includes("--url") ? argument("--url", "") : undefined;
  const specPath = resolve(ROOT, argument("--spec", SPEC_FILE));
  const outDir = resolve(ROOT, argument("--out", GENERATED_DIR));
  const check = process.argv.includes("--check");

  const spec = url ? await fetchSpec(url) : await readSpecFile(specPath);
  const generated = generate(spec);
  const files: Array<[string, string]> = [
    [resolve(outDir, "types.ts"), generated.types],
    [resolve(outDir, "client.ts"), generated.client],
    [resolve(ROOT, "spec/thin.json"), generated.thin],
  ];

  const report = JSON.parse(generated.thin) as ThinReport;
  const counts = report.counts;

  if (check) {
    const stale: string[] = [];
    for (const [path, content] of files) {
      let current = "";
      try {
        current = await readFile(path, "utf8");
      } catch {
        current = "";
      }
      if (current !== content) stale.push(path);
    }
    if (stale.length > 0) {
      console.error(`generated client is stale: ${stale.join(", ")}`);
      console.error("run: bun run generate:rimworld-client");
      process.exit(1);
    }
    console.log(`${counts.operations} operations, generated files are up to date`);
  } else {
    for (const [path, content] of files) {
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, content);
    }
    console.log(
      `${counts.operations} operations: ${counts.typedRoutes} typed routes, ` +
        `${counts.untypedRoutes} untyped, ${counts.freeFormFields} free-form fields`,
    );
    for (const [path] of files) console.log(`  ${path.replace(`${ROOT}/`, "")}`);
  }
}
